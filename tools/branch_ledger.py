#!/usr/bin/env python3
"""Read-only branch / tag recovery ledger (docs/ENGINEERING_POLICY.md, section "Branch accounting").

  branch_ledger.py              print the ledger as markdown
  branch_ledger.py --write      write docs/BRANCH_LEDGER.md
  branch_ledger.py --check      exit 1 if a branch has work outside the authoritative line without a recorded disposition
Only inspects Git history; never changes anything. Needs the remote refs (git fetch --all --tags).
"""
import datetime, json, os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))

def git(*a):
    return subprocess.run(["git", "-C", ROOT, *a], capture_output=True, text=True).stdout.strip()

def load():
    rel = json.load(open(os.path.join(ROOT, "release", "release.json")))
    disp = json.load(open(os.path.join(ROOT, "release", "branch_dispositions.json")))
    return rel, disp

def rows():
    rel, disp = load()
    auth = "origin/" + rel["authoritative_branch"]
    auth_sha = git("rev-parse", auth)
    out = []
    for b in git("for-each-ref", "--format=%(refname:short)", "refs/remotes/origin").splitlines():
        if b in ("origin", "origin/HEAD") or b == auth:
            continue
        sha = git("rev-parse", b)
        ahead = int(git("rev-list", "--count", auth + ".." + b) or 0)
        behind = int(git("rev-list", "--count", b + ".." + auth) or 0)
        cherry = git("cherry", auth, b).splitlines()
        unique = [l[2:] for l in cherry if l.startswith("+")]
        equiv = [l[2:] for l in cherry if l.startswith("-")]
        mb = git("merge-base", auth, b)
        if ahead == 0:
            cls, dispo, ok = "Already integrated (every commit is an ancestor of the authoritative branch)", "Kept as history; no action.", True
        elif b in disp:
            cls, dispo, ok = disp[b]["classification"], disp[b]["disposition"], True
        else:
            cls, dispo, ok = "UNKNOWN - requires owner review", "Has %d commit(s) not in the authoritative line." % ahead, False
        out.append({"branch": b, "sha": sha, "merge_base": mb[:12] if mb else "(none: unrelated history)", "ahead": ahead, "behind": behind,
                    "patch_unique": len(unique), "patch_equivalent": len(equiv), "classification": cls, "disposition": dispo, "ok": ok,
                    "subject": git("log", "-1", "--format=%s", b)[:90]})
    return rel, auth, auth_sha, out

def tags_on_auth(auth):
    bad = []
    for t in git("tag", "-l").splitlines():
        if subprocess.run(["git", "-C", ROOT, "merge-base", "--is-ancestor", t + "^{commit}", auth]).returncode != 0:
            bad.append(t)
    return bad

def markdown():
    rel, auth, auth_sha, rs = rows()
    bad_tags = tags_on_auth(auth)
    md = ["# Branch and release ledger", "",
          "Generated by `tools/branch_ledger.py` (read-only). Authoritative development line: `%s` @ `%s`." % (rel["authoritative_branch"], auth_sha[:12]), "",
          "| Branch | Tip | Merge base | Commits not on the authoritative line | Patch-unique / equivalent | Classification | Disposition |", "|---|---|---|---|---|---|---|"]
    for r in rs:
        md.append("| `%s` | `%s` | `%s` | %d (behind %d) | %d / %d | %s | %s |" % (r["branch"], r["sha"][:12], r["merge_base"], r["ahead"], r["behind"], r["patch_unique"], r["patch_equivalent"], r["classification"], r["disposition"]))
    _, disp = load()
    md += ["", "## Content-level findings (files present on older branch tips but not on the authoritative line)", "", "| Where | Paths | Classification | Note |", "|---|---|---|---|"]
    for f in disp.get("_content_findings", []):
        md.append("| %s | %s | %s | %s |" % (f["where"], f["paths"], f["classification"], f["note"]))
    md += ["", "## Tags", "", "Every tag is reachable from the authoritative branch." if not bad_tags else "Tags NOT reachable from the authoritative branch: " + ", ".join(bad_tags), ""]
    return "\n".join(md) + "\n", rs, bad_tags

def main():
    text, rs, bad_tags = markdown()
    if "--check" in sys.argv:
        bad = [r for r in rs if not r["ok"]]
        for r in bad:
            print("branch ledger: %s has %d commit(s) outside the authoritative line and no recorded disposition (release/branch_dispositions.json)" % (r["branch"], r["ahead"]))
        for t in bad_tags:
            print("branch ledger: tag %s is not on the authoritative line" % t)
        print("branch ledger: %d branches checked, %d unaccounted" % (len(rs), len(bad) + len(bad_tags)))
        sys.exit(1 if bad or bad_tags else 0)
    if "--write" in sys.argv:
        open(os.path.join(ROOT, "docs", "BRANCH_LEDGER.md"), "w").write(text)
        print("wrote docs/BRANCH_LEDGER.md")
    else:
        print(text)

if __name__ == "__main__":
    main()
